-- ------------------------------------------------------------
-- 2) Perfil de salud del usuario
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  full_name   text,
  ficha       text,
  email       text,
  age         int,
  height      numeric,
  weight      numeric,
  goal        text,
  preferences jsonb default '[]',
  created_at  timestamptz default now()
);

-- Crea el perfil automáticamente cuando un usuario se registra
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, ficha, email)
  values (new.id, new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'ficha', new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ------------------------------------------------------------
-- 3) Favoritos
-- ------------------------------------------------------------
create table if not exists public.favorites (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  rec_id     bigint not null references public.recommendations(id) on delete cascade,
  created_at timestamptz default now(),
  unique (user_id, rec_id)
);

-- ------------------------------------------------------------
-- 4) Seguimiento de hábitos
-- ------------------------------------------------------------
create table if not exists public.habits (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  name       text not null,
  target     text,
  progress   numeric default 0,
  done       boolean default false,
  updated_at timestamptz default now(),
  unique (user_id, name)
);

-- ------------------------------------------------------------
-- 5) Seguridad (Row Level Security)
-- ------------------------------------------------------------
alter table public.recommendations enable row level security;
alter table public.profiles        enable row level security;
alter table public.favorites       enable row level security;
alter table public.habits          enable row level security;

-- Las recomendaciones son públicas (cualquiera puede leerlas)
drop policy if exists "recs_read_all" on public.recommendations;
create policy "recs_read_all" on public.recommendations
  for select using (true);

-- Cada usuario solo ve y edita su propio perfil
drop policy if exists "profiles_own" on public.profiles;
create policy "profiles_own" on public.profiles
  for all using (auth.uid() = id) with check (auth.uid() = id);

-- Cada usuario gestiona solo sus favoritos
drop policy if exists "favs_own" on public.favorites;
create policy "favs_own" on public.favorites
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Cada usuario gestiona solo sus hábitos
drop policy if exists "habits_own" on public.habits;
create policy "habits_own" on public.habits
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

